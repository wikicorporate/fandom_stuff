    }
}

-- Функция, которую будет вызывать JS для конвертации таблицы в JSON
function p.toJSON()
    return mw.text.jsonEncode(templates)
end

-- Функция, которая отдает сам текст шаблона при вызове через {{#invoke:Модерация|main|ИмяШаблона}}
function p.main(frame)
    -- Получаем имя шаблона (которое передает скрипт, например, "Block" или "Предупреждение")
    local tplName = frame.args[1]
    if not tplName then return "" end
    
    -- Ищем шаблон в нашей базе данных по параметру 'name'
    for key, data in pairs(templates) do
        if data.name == tplName then
            if data.text then
                -- frame:preprocess прогоняет текст через движок MediaWiki, 
                -- чтобы сработали внутренние ссылки, жирный текст и HTML-теги
                return frame:preprocess(data.text)
            else
                return "''Ошибка: Текст для данного шаблона не задан в модуле.''"
            end
        end
    end
    
    return "''Ошибка: Шаблон не найден в базе данных модуля.''"
end

return p
