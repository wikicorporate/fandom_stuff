local data = {
    -- Базовые форматы
    ['B'] = "'''$1'''",             -- Жирный
    ['I'] = "''$1''",              -- Курсив
    ['BI'] = "'''''$1'''''",       -- Жирный курсив
    ['U'] = "<u>$1</u>",           -- Подчёркнутый
    ['S'] = "<s>$1</s>",           -- Зачёркнутый
    
    -- Блочные и технические
    ['CODE'] = "<code>$1</code>",  -- Код
    ['KBD'] = "<kbd>$1</kbd>",     -- Клавиша
    ['PRE'] = "<pre>$1</pre>",     -- Преформатирование
    ['NOWIKI'] = "<nowiki>$1</nowiki>", -- Без вики-разметки
    
    -- Размеры
    ['SMALL'] = "<small>$1</small>",
    ['BIG'] = "<big>$1</big>",
    ['SUB'] = "<sub>$1</sub>",     -- Нижний индекс
    ['SUP'] = "<sup>$1</sup>",     -- Верхний индекс
    
    -- Специфичные
    ['SPOILER'] = '<span class="spoiler">$1</span>',
    ['HIDDEN'] = '<!-- $1 -->',    -- Скрытый комментарий (виден только в коде)
}

-- Таблица синонимов (алиасов) для удобства редакторов
local aliases = {
    ['BOLD'] = 'B', ['ЖИРНЫЙ'] = 'B', ['Ж'] = 'B', ['3'] = 'B', ['ТРИ'] = 'B',
    ['ITALIC'] = 'I', ['КУРСИВ'] = 'I', ['К'] = 'I',
    ['BOLDITALIC'] = 'BI', ['ЖИ'] = 'BI',
    ['UNDERLINE'] = 'U', ['ПОДЧЕРКНУТЫЙ'] = 'U', ['П'] = 'U',
    ['STRIKE'] = 'S', ['ЗАЧЕРКНУТЫЙ'] = 'S', ['З'] = 'S',
    ['КОД'] = 'CODE',
    ['КЛАВИША'] = 'KBD',
    ['ПРЕ'] = 'PRE',
    ['БЕЗВИКИ'] = 'NOWIKI',
    ['МЕЛКИЙ'] = 'SMALL',
    ['КРУПНЫЙ'] = 'BIG',
    ['НИЖНИЙ'] = 'SUB',
    ['ВЕРХНИЙ'] = 'SUP',
    ['СПОЙЛЕР'] = 'SPOILER',
    ['СКРЫТЫЙ'] = 'HIDDEN', ['КОММЕНТАРИЙ'] = 'HIDDEN'
}

-- Автоматически вшиваем синонимы в основную базу (для совместимости с mw.loadData)
for alias, key in pairs(aliases) do
    data[alias] = data[key]
end

return data
